-- Testes para dados extraídos do commit Survev c6185e31...
-- Executável sem love.graphics.
local Camera = require("src.survev.camera")
local Binds = require("src.survev.input_bindings")
local Config = require("src.survev.game_config")

assert(Config.protocolVersion == 1028)
assert(Config.player.radius == 1)
assert(Config.player.health == 100)
assert(Config.player.moveSpeed == 12)
assert(Config.player.reviveDuration == 8)
assert(Config.map.gridSize == 16)
assert(Config.scopeZoomRadius.desktop["15xscope"] == 104)
assert(Config.TeamMode.Solo == 1 and Config.TeamMode.Squad == 4)

local cam = Camera.new()
assert(cam.m_ppu == 16 and cam.m_zoom == 1.5)
assert(cam:m_z() == 24)
cam.m_screenWidth, cam.m_screenHeight = 1280, 720
cam.m_pos = {x = 300, y = 225}
local center = cam:m_pointToScreen({x = 300, y = 225})
assert(center.x == 640 and center.y == 360)
local screen = cam:m_pointToScreen({x = 312, y = 230})
assert(screen.x == 928 and screen.y == 240)
local world = cam:m_screenToPoint(screen)
assert(world.x == 312 and world.y == 230)
assert(cam:m_pixels(2) == 3)
assert(cam:m_scaleToScreen(2) == 48)
cam:m_addShake({x = 300, y = 225}, 7)
assert(cam.m_shakeInt == 7)
cam:m_applyShake(function(v) return {x = v, y = 0} end)
assert(cam.m_pos.x == 307 and cam.m_shakeInt == 0)

assert(Binds.Input.Count == 36)
assert(Binds.Input.MoveLeft == 0 and Binds.Input.TeamPingSingle == 35)
assert(Binds.default.Interact[2] == "f", "Interacao deve ser F, nao E")
assert(Binds.default.StowWeapons[2] == "e")
assert(Binds.default.UseHealthKit[2] == "8")
local fire = Binds.actionsFor("mouse", 1)
assert(#fire == 1 and fire[1] == Binds.Input.Fire)
local reload = Binds.actionsFor("key", "r")
assert(#reload == 1 and reload[1] == Binds.Input.Reload)
local interact = Binds.actionsFor("key", "f")
assert(#interact == 1 and interact[1] == Binds.Input.Interact)
print("Survev Lua parity checks passed")
